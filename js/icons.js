/**
 * Procura todos os elementos [data-icon] e injeta o SVG correspondente.
 * Idempotente — se já tiver conteúdo, substitui.
 */
export function injectIcons(root = document) {
  const els = root.querySelectorAll('[data-icon]');
  els.forEach(el => {
    const name = el.getAttribute('data-icon');
    const svg = ICONS[name];
    if (svg) {
      el.innerHTML = svg;
    } else {
      console.warn('[icons] Icone desconhecido:', name);
    }
  });
}

export default { ICONS, injectIcons };
